source("New_simulations/dm_adaptive_tempering/support.R")
source("New_simulations/dm_adaptive_tempering/math.R")
source("New_simulations/dm_adaptive_tempering/runner.R")
apt_environment()
o <- apt_options(c("ladder", "control", "workers"))
ladder <- as.integer(apt_get(o, "ladder", Sys.getenv("SGE_TASK_ID", "0")))
control <- apt_get(o, "control", "false")
apt_need(control %in% c("true", "false"), "control must be true/false")
control <- control == "true"
workers <- as.integer(apt_get(o, "workers", Sys.getenv("NSLOTS", "1")))
z <- apt_load(); apt_gate()
apt_need(workers <= as.integer(Sys.getenv("NSLOTS", as.character(workers))), "Workers exceed requested CPU slots")
if (control) workers <- 1L
out <- file.path("New_simulations/outputs/dm_apt10_v1", sprintf("%s_%02d", if (control) "control" else "ladder", ladder))
apt_run(z$inputs, z$plan, ladder, control, out, workers)
cat("APT TASK COMPLETE\n")
